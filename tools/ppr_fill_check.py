"""Where the top-10 of Monte Carlo PPR comes from under the chosen rules (explains Section 6.6).

    python tools/ppr_fill_check.py --driver-memory 14g

Same users, seeds and scores as tools/ppr_exact.py (user_time val stage, 2,000 users, chosen alpha,
beta and min_visits). For each W it reports how many unseen movies keep at least min_visits visits,
how many top-10 slots top_k fills with the most popular unseen movies because too few movies are
left, how many of the fill slots and of the slots chosen by the walks are in the exact top 10, and
how many walk-chosen movies have fewer than 2 * min_visits visits. Writes reports/ppr_fill_check.md.
"""
import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.common import REPORTS, SEED, get_spark, load_stage  # noqa: E402
from src.methods._shared import build_index, row  # noqa: E402
from src.methods.ppr import walk_counts  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ppr_exact as pe  # noqa: E402
from member import chosen_params  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", default="user_time")
    ap.add_argument("--users", type=int, default=2000)
    ap.add_argument("--walkers", type=int, nargs="+", default=[100, 250, 1000, 2500])
    ap.add_argument("--driver-memory", default="8g")
    args = ap.parse_args()

    _, ch = chosen_params("ppr")
    alpha, n_steps = float(ch.get("alpha", 0.3)), int(ch.get("n_steps", 20))
    beta, min_visits = float(ch.get("beta", 0.0)), int(ch.get("min_visits", 1))

    spark = get_spark("ppr-fill-check", driver_memory=args.driver_memory)
    try:
        train, _ = load_stage(spark, args.split, "val")
        d = build_index(train.cache())
        has_like = np.flatnonzero(np.diff(d["liked_ptr"]) > 0)
        users = np.intersect1d(d["users"], has_like)
        rng = np.random.default_rng(SEED)
        sample = np.sort(rng.choice(users, size=min(args.users, len(users)), replace=False))
        batches = [sample[i:i + pe.BATCH] for i in range(0, len(sample), pe.BATCH)]
        penalty = np.maximum(d["n_likes"], 1).astype(np.float64) ** -beta
        p_um, p_mu = pe.transition_matrices(d)
        ex = np.vstack([pe.exact_counts(b, p_um, p_mu, alpha, 1, n_steps) for b in batches])
        ex_pen = pe.top_lists(ex * penalty[None, :], sample, d, 10)
        pop_rank = np.full(d["n_items"], len(d["pop_order"]))
        pop_rank[d["pop_order"]] = np.arange(1, len(d["pop_order"]) + 1)
        ex_items = np.concatenate([ex_pen[int(u)] for u in sample])
        median_rank = float(np.median(pop_rank[ex_items]))

        rows = []
        for W in args.walkers:
            mc = np.vstack([walk_counts(b, d, alpha, W, n_steps, np.random.default_rng([SEED, int(b[0])]))
                            for b in batches])
            filt = mc.copy()
            filt[filt < min_visits] = 0
            lists = pe.top_lists(filt * penalty[None, :], sample, d, 10)
            kept, n_fill, hit_fill, n_walk, hit_walk, n_low = [], 0, 0, 0, 0, 0
            for j, u in enumerate(sample):
                ok = filt[j] > 0
                ok[row(d["rated_ptr"], d["rated_idx"], u)] = False
                kept.append(int(ok.sum()))
                exact = set(ex_pen[int(u)])
                for i in lists[int(u)]:
                    if ok[i]:
                        n_walk, hit_walk, n_low = n_walk + 1, hit_walk + (i in exact), n_low + (mc[j, i] < 2 * min_visits)
                    else:
                        n_fill, hit_fill = n_fill + 1, hit_fill + (i in exact)
            kept = np.array(kept)
            r = {"W": W, "overlap": pe.overlap(ex_pen, lists, 10), "kept_median": float(np.median(kept)),
                 "few_kept": float(np.mean(kept < 10)), "fill": n_fill / (n_fill + n_walk),
                 "fill_hit": hit_fill / n_fill if n_fill else None, "walk_hit": hit_walk / n_walk if n_walk else None,
                 "walk_low": n_low / n_walk if n_walk else None}
            rows.append(r)
            print(r)
    finally:
        spark.stop()

    def pct(x):
        return "n/a" if x is None else f"{100 * x:.1f}%"

    lines = ["# Where the Monte Carlo PPR top 10 comes from (generated by tools/ppr_fill_check.py)", "",
             f"`{args.split}` validation stage (training part only), the same {len(sample):,} users and seeds as "
             f"`reports/ppr_exact.md`; chosen rules: beta {beta} on both sides, min_visits {min_visits} on the Monte Carlo side.",
             f"Median popularity rank of the movies in the exact top 10 with the penalty: {median_rank:g} "
             "(1 = the most liked movie).", "",
             f"| Walkers W | Overlap@10, chosen rules | Unseen movies with >= {min_visits} visits (median per user) | "
             f"Users with < 10 such movies | Top-10 slots filled by popularity | Fill slots in exact top 10 | "
             f"Walk slots in exact top 10 | Walk slots with < {2 * min_visits} visits |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['W']:,} | {r['overlap']:.4f} | {r['kept_median']:g} | {pct(r['few_kept'])} | {pct(r['fill'])} | "
                     f"{pct(r['fill_hit'])} | {pct(r['walk_hit'])} | {pct(r['walk_low'])} |")
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "ppr_fill_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print("-> reports/ppr_fill_check.md")


if __name__ == "__main__":
    main()

"""Growth curves and break-even sizes (RQ3) from the scalability runs.

    python tools/growth.py

Reads results/<method>/user_time/val__scale_c4[_s<pct>]/metrics.json (4 cores; 10/25/50/100% of the
users) and fits t = a * N^b by least squares on log t against log N, where N is the number of
evaluated users of the run and t the recommend time. The fit uses the 25%, 50% and 100% runs: at 10%
fixed Spark overhead is a large part of the time. Writes
  reports/growth.md, reports/growth.json        exponent b, a, R^2, time predicted for 10x the users
  report/figures/time_vs_users_loglog.png        log-log plot with the fitted lines
and, for each exact/approximate pair (kNN / LSH), the size N* where the two fitted curves cross:
a1 * N^b1 = a2 * N^b2  ->  N* = (a2 / a1)^(1 / (b1 - b2)). A crossing exists only below or above the
measured range when the approximation grows more slowly; the table says which.

The 10x prediction keeps the movie catalogue fixed and only scales the users, like the samples do.
It is an extrapolation of three points and is only as good as the power law.
"""
import json
from pathlib import Path

import numpy as np

import matplotlib
import matplotlib.ticker

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
METHODS = ["popularity", "knn", "lsh", "ppr", "als"]
NAMES = {"popularity": "popularity", "knn": "exact kNN", "lsh": "LSH", "ppr": "PPR", "als": "ALS"}
SAMPLES = [10, 25, 50, 100]
FIT_FROM = 25
PAIRS = [("knn", "lsh")]


def runs(method):
    out = []
    for pct in SAMPLES:
        tag = "scale_c4" + (f"_s{pct:g}" if pct < 100 else "")
        f = RESULTS / method / "user_time" / f"val__{tag}" / "metrics.json"
        if f.exists():
            m = json.loads(f.read_text(encoding="utf-8"))
            out.append((pct, m["evaluated_users"], m["seconds_recommend"]))
    return out


def fit(points):
    pts = [(n, t) for pct, n, t in points if pct >= FIT_FROM]
    if len(pts) < 2:
        return None
    x, y = np.log([p[0] for p in pts]), np.log([p[1] for p in pts])
    b, loga = np.polyfit(x, y, 1)
    pred = loga + b * x
    r2 = 1 - ((y - pred) ** 2).sum() / max(((y - y.mean()) ** 2).sum(), 1e-12)
    return {"a": float(np.exp(loga)), "b": float(b), "r2": float(r2)}


def main():
    data = {m: runs(m) for m in METHODS}
    fits = {m: fit(p) for m, p in data.items() if p}
    n_full = max(n for p in data.values() for _, n, _ in p)
    res = {"fit_from_pct": FIT_FROM, "users_at_100pct": n_full, "methods": {}, "pairs": []}
    for m, f in fits.items():
        if not f:
            continue
        t100 = next(t for pct, _, t in data[m] if pct == 100)
        res["methods"][m] = {**f, "seconds_at_100pct": t100,
                             "predicted_seconds_10x": f["a"] * (10 * n_full) ** f["b"],
                             "points": [{"pct": p, "users": n, "seconds": t} for p, n, t in data[m]]}
    for ex, ap in PAIRS:
        if ex in res["methods"] and ap in res["methods"]:
            f1, f2 = res["methods"][ex], res["methods"][ap]
            n_lo, n_hi = min(p["users"] for p in f1["points"]), n_full
            row = {"exact": ex, "approximation": ap, "b_exact": f1["b"], "b_approx": f2["b"]}
            if f2["b"] < f1["b"] - 1e-9:
                n_star = (f2["a"] / f1["a"]) ** (1 / (f1["b"] - f2["b"]))
                row.update({"crossing_users": n_star, "inside_measured_range": n_lo <= n_star <= n_hi,
                            "verdict": "approximation becomes cheaper above N*"})
            else:
                row.update({"crossing_users": None, "verdict": "no crossing: the approximation grows at least as fast"})
            res["pairs"].append(row)

    (ROOT / "reports" / "growth.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    L = ["# Growth of recommend time with the number of users (generated by tools/growth.py)", "",
         f"Fit t = a * N^b on the {FIT_FROM}%, 50% and 100% scalability runs (4 cores, one machine); N = evaluated "
         f"users ({n_full:,} at 100%). Prediction for 10x the users keeps the catalogue fixed.", "",
         "| Method | Exponent b | R^2 | Time at 100% (s) | Predicted at 10x users (s) |", "|---|---|---|---|---|"]
    for m, r in res["methods"].items():
        L.append(f"| {NAMES[m]} | {r['b']:.2f} | {r['r2']:.3f} | {r['seconds_at_100pct']:.2f} | {r['predicted_seconds_10x']:,.0f} |")
    L.append("")
    for p in res["pairs"]:
        if p["crossing_users"] is None:
            L.append(f"- {NAMES[p['approximation']]} vs {NAMES[p['exact']]}: exponents {p['b_approx']:.2f} vs "
                     f"{p['b_exact']:.2f}; {p['verdict']}.")
        else:
            where = "inside" if p["inside_measured_range"] else "outside (extrapolated)"
            L.append(f"- {NAMES[p['approximation']]} vs {NAMES[p['exact']]}: exponents {p['b_approx']:.2f} vs "
                     f"{p['b_exact']:.2f}; curves cross at about {p['crossing_users']:,.0f} users, {where} the measured range.")
    (ROOT / "reports" / "growth.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))

    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    colors = {"popularity": "#1f77b4", "knn": "#ff7f0e", "lsh": "#2ca02c", "ppr": "#d62728", "als": "#9467bd"}
    for m, r in res["methods"].items():
        n = np.array([p["users"] for p in r["points"]], float)
        t = np.array([p["seconds"] for p in r["points"]], float)
        ax.plot(n, t, "o", color=colors[m])
        xs = np.geomspace(n.min(), n.max(), 50)
        ax.plot(xs, r["a"] * xs ** r["b"], "-", color=colors[m], label=f"{NAMES[m]} (b = {r['b']:.2f})")
    ax.set_xscale("log")
    ax.set_yscale("log")
    plain = matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:,.0f}")
    for axis in (ax.xaxis, ax.yaxis):
        axis.set_major_formatter(plain)
        axis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.set_xticks([13_000, 32_000, 65_000, 130_000])
    ax.set_xlabel("evaluated users (log scale)")
    ax.set_ylabel("recommend time, s (log scale)")
    ax.set_title("Recommend time against users, 4 cores (fit: t = a N^b)")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    out = ROOT / "report" / "figures" / "time_vs_users_loglog.png"
    fig.savefig(out, dpi=150)
    print(f"-> reports/growth.md, {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

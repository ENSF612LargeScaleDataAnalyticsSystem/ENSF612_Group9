"""Turn results/summary.csv (+ metrics.json) into the report tables: reports/results.md.

    python tools/summarize.py

Sections:
  1. tuning: every pilot validation run per method, best NDCG@10 marked
  2. test results on user_time and global_time with 95% intervals (latest run of each method)
  3. scalability: recommend time against user sample (4 cores) and against cores (25% sample)
The latest row wins when the same configuration was run more than once.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
METHODS = ["popularity", "knn", "lsh", "ppr", "als"]


def load():
    rows = list(csv.DictReader(open(RESULTS / "summary.csv", encoding="utf-8")))
    latest = {}
    for r in rows:                                    # later rows overwrite earlier ones
        latest[(r["method"], r["split"], r["stage"], r["tag"])] = r
    return list(latest.values())


def metrics_json(r):
    folder = RESULTS / r["method"] / r["split"] / (r["stage"] + (f"__{r['tag']}" if r["tag"] else ""))
    p = folder / "metrics.json"
    return json.loads(p.read_text()) if p.exists() else {}


def f4(x):
    return f"{float(x):.4f}"


def ci(m, key):
    v = m.get(f"{key}_ci95")
    return f" [{v[0]:.4f}, {v[1]:.4f}]" if v else ""


def main():
    rows = load()
    out = ["# Results (generated by tools/summarize.py)\n"]

    out.append("## 1. Tuning on user_time_10pct, validation stage\n")
    for m in METHODS:
        tune = [r for r in rows if r["method"] == m and r["split"] == "user_time_10pct" and r["stage"] == "val"]
        if not tune:
            continue
        best = max(tune, key=lambda r: float(r["ndcg@10"]))
        out.append(f"### {m}\n\n| Tag | Params | P@10 | R@10 | NDCG@10 | Coverage | Recommend s |\n|---|---|---|---|---|---|---|")
        for r in sorted(tune, key=lambda r: -float(r["ndcg@10"])):
            mark = " **best**" if r is best else ""
            out.append(f"| {r['tag'] or '-'}{mark} | `{r['params']}` | {f4(r['precision@10'])} | {f4(r['recall@10'])} | "
                       f"{f4(r['ndcg@10'])} | {f4(r['coverage'])} | {float(r['seconds_recommend']):.0f} |")
        out.append("")

    for split in ("user_time", "global_time"):
        test = [r for r in rows if r["split"] == split and r["stage"] == "test"]
        if not test:
            continue
        out.append(f"## 2. Test results on {split}\n")
        out.append("| Method | Params | P@10 [95% CI] | R@10 [95% CI] | NDCG@10 [95% CI] | Coverage | Users | Recommend s |")
        out.append("|---|---|---|---|---|---|---|---|")
        for m in METHODS:
            rs = [r for r in test if r["method"] == m]
            if not rs:
                continue
            r = max(rs, key=lambda r: r["finished_utc"])
            j = metrics_json(r)
            out.append(f"| {m} | `{r['params']}` | {f4(r['precision@10'])}{ci(j, 'precision@10')} | "
                       f"{f4(r['recall@10'])}{ci(j, 'recall@10')} | {f4(r['ndcg@10'])}{ci(j, 'ndcg@10')} | "
                       f"{f4(r['coverage'])} | {int(r['evaluated_users']):,} | {float(r['seconds_recommend']):.0f} |")
        out.append("")

    scale = [r for r in rows if r["split"] == "user_time" and r["tag"].startswith("scale_")]
    if scale:
        def sample_of(r):
            for part in r["tag"].split("_"):
                if part.startswith("s") and part[1:].replace(".", "").isdigit():
                    return float(part[1:])
            return 100.0
        out.append("## 3. Scalability (user_time, validation stage)\n")
        out.append("Recommend time in seconds; NDCG@10 in brackets.\n")
        out.append("### Data size (4 cores)\n\n| Method | 10% | 25% | 50% | 100% |\n|---|---|---|---|---|")
        for m in METHODS:
            cells = []
            for s in (10, 25, 50, 100):
                r = [x for x in scale if x["method"] == m and x["cores"] == "4" and sample_of(x) == s]
                cells.append(f"{float(r[0]['seconds_recommend']):.0f} ({f4(r[0]['ndcg@10'])})" if r else "-")
            if any(c != "-" for c in cells):
                out.append(f"| {m} | " + " | ".join(cells) + " |")
        out.append("\n### Cores (25% sample)\n\n| Method | 1 | 2 | 4 | Speed-up 1→4 |\n|---|---|---|---|---|")
        for m in METHODS:
            t = {}
            for c in ("1", "2", "4"):
                r = [x for x in scale if x["method"] == m and x["cores"] == c and sample_of(x) == 25]
                if r:
                    t[c] = float(r[0]["seconds_recommend"])
            if t:
                sp = f"{t['1'] / t['4']:.2f}×" if "1" in t and "4" in t else "-"
                out.append(f"| {m} | " + " | ".join(f"{t[c]:.0f}" if c in t else "-" for c in ("1", "2", "4")) + f" | {sp} |")
        out.append("")

    path = ROOT / "reports" / "results.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    sys.exit(main())
